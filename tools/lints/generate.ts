#!/usr/bin/env bun
// Tooling catalogue plus Spec tags/properties, the Session Commands and the
// Fuel estimate's tables and the save format's structure, copied for browser
// workers and the save decoder.
import catalogue from '../../tooling/stack/lints.toml';
import costs from '../../spec/data/costs.toml';
import grammar from '../../spec/data/grammar.toml';
import machine from '../../spec/data/machine.toml';
import saveFormat from '../../spec/data/save-format.toml';
import session from '../../spec/data/session.toml';
import { builtins } from '../../impl/ts/src/generated/syntax';
import { costModel } from '../../impl/ts/src/generated/machine';
import { resolve } from 'node:path';

type Entry = {
  beginner: 'off' | 'hint' | 'warning';
  fix?: string;
  flags: string;
  id: string;
  message: string;
  standard: 'off' | 'hint' | 'warning';
  status: 'implemented' | 'planned';
};
const entries = catalogue.lint as Entry[];
const ids = new Set<string>();
for (const entry of entries) {
  if (
    !/^[a-z]+(?:-[a-z]+)*$/.test(entry.id) ||
    ids.has(entry.id) ||
    !['off', 'hint', 'warning'].includes(entry.beginner) ||
    !['off', 'hint', 'warning'].includes(entry.standard) ||
    !['implemented', 'planned'].includes(entry.status) ||
    !entry.flags ||
    !entry.message
  ) {
    throw new Error(`Invalid Lint catalogue entry: ${entry.id}`);
  }
  ids.add(entry.id);
}
const threshold = catalogue.settings.long_join_body_lines as number;
if (!Number.isInteger(threshold) || threshold < 0) {
  throw new Error('The Join line threshold must be a nonnegative integer');
}
const content =
  '// Generated by tools/lints/generate.ts. Do not edit.\n' +
  `export const lintCatalogue = ${JSON.stringify(entries, null, 2)} as const;\n` +
  `export const longJoinBodyLines = ${threshold};\n` +
  `export const advancedTags = ${JSON.stringify(grammar.advanced, null, 2)} as const;\n` +
  `export const properties = ${JSON.stringify(grammar.properties, null, 2)} as const;\n` +
  `export const builtins = ${JSON.stringify(
    builtins.map(({ name, kind }) => ({ name, kind })),
    null,
    2,
  )} as const;\n`;
type Command = { does: string; name: string; usage: string };
const commands = (session.command as Command[]).map(
  ({ name, usage, does }) => ({
    name,
    usage,
    does,
  }),
);
const sessionContent =
  '// Generated by tools/lints/generate.ts from spec/data/session.toml. Do not edit.\n' +
  `export const sessionCommands = ${JSON.stringify(commands, null, 2)} as const;\n`;
// An instruction's `rate` indexes costs.toml's rates in order. Each Fuel
// formula splits into its constant and the terms that measure values.
type Rate = { fuel: string; key: string };
const rates = (costs.rate as Rate[]).map(({ key, fuel }, i) => {
  if (costModel.rates[i]?.key !== key) {
    throw new Error(`Cost Model rate ${i} is not ${key}`);
  }
  const terms = fuel.split(' + ');
  const fixed = terms.filter(t => /^\d+$/.test(t)).map(Number);
  return {
    key,
    fixed: fixed.reduce((a, b) => a + b, 0),
    open: terms.filter(t => !/^\d+$/.test(t)),
  };
});
// Instructions that never continue to the next one. A label is always an
// instruction's last operand.
const ends = [
  'jump',
  'return',
  'clause-fail',
  'throw',
  'raise',
  'veto',
  'pass',
];
type Opcode = { name: string; operands: string[] };
const opcodes = machine.instruction as Opcode[];
for (const name of ends) {
  if (!opcodes.some(op => op.name === name)) {
    throw new Error(`machine.toml has no ${name}`);
  }
}
for (const op of opcodes) {
  // The count's index is fixed only if no optional operand precedes it.
  if (
    op.operands.includes('count') &&
    op.operands
      .slice(0, op.operands.indexOf('count'))
      .some(o => o.endsWith('?'))
  ) {
    throw new Error(`${op.name}'s count follows an optional operand`);
  }
  const at = op.operands.indexOf('label');
  if (at !== -1 && at !== op.operands.length - 1) {
    throw new Error(`${op.name}'s label is not its last operand`);
  }
}
const fuelContent =
  '// Generated by tools/lints/generate.ts from spec/data/costs.toml and machine.toml. Do not edit.\n' +
  `export const fuelRates = ${JSON.stringify(rates, null, 2)} as const;\n` +
  `export const jumping = ${JSON.stringify(
    opcodes.filter(op => op.operands.includes('label')).map(op => op.name),
    null,
    2,
  )} as const;\n` +
  `export const ending = ${JSON.stringify(ends, null, 2)} as const;\n` +
  `export const countAt = ${JSON.stringify(
    Object.fromEntries(
      opcodes
        .filter(op => op.operands.includes('count'))
        .map(op => [op.name, op.operands.indexOf('count')]),
    ),
    null,
    2,
  )} as Readonly<Record<string, number>>;\n`;
// The save format's structure, for the save decoder. A field that is written
// only when another is none says so in its prose; that becomes `unless`.
type SaveField = { is: string; name: string; type: string; unless?: string };
const saveFields = (fields: SaveField[] = []) =>
  fields.map(({ name, type, is }) => {
    const only = /only when `([^`]+)` is none/.exec(is);
    if (!only && /only when/i.test(is)) {
      throw new Error(`save-format.toml: unreadable condition on ${name}`);
    }
    return only ? { name, type, unless: only[1] } : { name, type };
  });
type SaveStructure = {
  field?: SaveField[];
  name: string;
  required?: boolean;
  tag?: number;
  variant?: { field?: SaveField[]; name: string; tag: number }[];
};
const saveContent =
  '// Generated by tools/lints/generate.ts from spec/data/save-format.toml. Do not edit.\n' +
  `export const saveSchema = ${JSON.stringify(
    {
      magic: saveFormat.format.magic,
      version: saveFormat.format.version,
      header: saveFields(saveFormat.header),
      records: (saveFormat.record as SaveStructure[]).map(r => ({
        name: r.name,
        fields: saveFields(r.field),
      })),
      unions: (saveFormat.union as SaveStructure[]).map(u => ({
        name: u.name,
        variants: (u.variant ?? []).map(v => ({
          tag: v.tag,
          name: v.name,
          fields: saveFields(v.field),
        })),
      })),
      sections: (saveFormat.section as SaveStructure[]).map(s => ({
        tag: s.tag,
        name: s.name,
        required: s.required,
        fields: saveFields(s.field),
      })),
    },
    null,
    2,
  )} as const;\n`;
const generated = resolve(import.meta.dir, '../../tooling/stack/src/generated');
const files: [string, string][] = [
  [resolve(generated, 'lints.ts'), content],
  [resolve(generated, 'session.ts'), sessionContent],
  [resolve(generated, 'fuel.ts'), fuelContent],
  [resolve(generated, 'save-format.ts'), saveContent],
];
for (const [path, text] of files) {
  if (process.argv.includes('--check')) {
    if (
      !(await Bun.file(path).exists()) ||
      (await Bun.file(path).text()) !== text
    ) {
      throw new Error('Tooling tables are stale; run bun run lints:generate');
    }
  } else {
    await Bun.write(path, text);
  }
}
