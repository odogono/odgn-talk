import type { CompiledCostModel, CostTerm } from './compile';

/** Emit ordinary browser-safe functions; formula text is never executed at runtime. */
export const emitTsCosts = (model: CompiledCostModel): string => {
  const expression = (terms: readonly CostTerm[], sizing = false): string =>
    terms
      .map(([measure, subject, factor, divisor]) => {
        let value: string;
        if (measure === 0) {
          return String(Math.ceil(factor / divisor));
        }
        const name = model.measures[measure]!;
        if (sizing) {
          value = `measure(${measure}, v)`;
        } else if (subject === 0) {
          // Unimplemented count measures have the evaluator's zero default.
          value = ['scanned', 'steps', 'frames', 'count', 'declared'].includes(
            name,
          )
            ? `(m.${name} ?? 0)`
            : '0';
        } else {
          const target =
            subject === 1
              ? 'm.input'
              : subject === 2
                ? 'm.result'
                : subject === 3
                  ? 'undefined'
                  : `m.x?.[${subject - 4}]`;
          value = `measure(${measure}, ${target})`;
          if (name === 'size' && (subject === 1 || subject === 2)) {
            value = `(m.${subject === 1 ? 'input' : 'result'}Size ?? ${value})`;
          }
        }
        // Keep each term's multiply/divide/ceil order, including / 1:
        // range counts can exceed the exact-integer range of a JS number.
        return `Math.ceil((${factor} * ${value}) / ${divisor})`;
      })
      .join(' + ') || '0';

  return (
    '// Generated by tools/syntax/generate.ts from spec/data/costs.toml. Do not edit.\n' +
    "import type { Charge, Measured } from '../costs';\n" +
    "import type { Value } from '../values';\n" +
    'type Measure = (code: number, value: Value | undefined) => number;\n' +
    'export const makeCostRates = (measure: Measure): readonly ((m: Measured) => Charge)[] => [\n' +
    model.rates
      .map(
        ({ key, fuel, alloc }) =>
          `  // ${key}\n  (m) => ({ fuel: ${expression(fuel)}, alloc: ${expression(alloc)} }),\n`,
      )
      .join('') +
    '];\n' +
    'export const leafSize = (v: Value, measure: Measure): number | undefined => {\n' +
    // The size table also contains internal state parts. They cannot match
    // a public Value, but keeping them makes this independent of a kind list.
    '  switch (v.kind as string) {\n' +
    model.sizes
      // These measures can depend on child Values. All other formulas are leaves.
      .filter(({ terms }) =>
        terms.every(
          ([measure]) =>
            !['contents', 'size', 'items', 'entries'].includes(
              model.measures[measure]!,
            ),
        ),
      )
      .map(
        ({ of, terms }) =>
          `    case ${JSON.stringify(of)}: return ${expression(terms, true)};\n`,
      )
      .join('') +
    '  }\n};\n'
  );
};
