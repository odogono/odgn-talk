#!/usr/bin/env bun
// Writes, or with --check compares, the Fuel Estimate of every stdlib export
// (#1609). The stdlib's Fuel is normative, so a change to this file is a Cost
// Model change for its PR to call out.
import { resolve } from 'node:path';
import { codeOf, stdlibLibrary } from '../../impl/ts/src/library';
import { libraryExports } from '../../impl/ts/src/generated/syntax';
import { estimateFuel, fuelText } from '../../tooling/stack/src/fuel';

const path = resolve(import.meta.dir, 'stdlib-fuel.txt');

/** One listed term per line, so a diff shows the term that changed. */
const listed = (text: string) =>
  text.replaceAll(
    /^(\+ [^\n:]+:) (.+)$/gm,
    (_, label: string, items: string) =>
      `${label}\n${items
        .split(/, (?![^(]*\))/)
        .map(item => `    ${item}`)
        .join('\n')}`,
  );

export const stdlibFuel = (): string => {
  const blocks: string[] = [];
  const libraries = [...new Set(libraryExports.map(e => e.library))].sort();
  for (const library of libraries) {
    const estimates = estimateFuel(codeOf(stdlibLibrary(library)) as never);
    const exports = libraryExports
      .filter(e => e.library === library)
      .map(e => e.name)
      .sort();
    for (const name of exports) {
      const clauses = estimates.filter(e => e.name === name);
      blocks.push(
        `${library}.${name}\n` +
          (clauses.length
            ? clauses.map(e => listed(fuelText(e))).join('\n')
            : 'a Constant, with no Fuel of its own'),
      );
    }
  }
  return (
    '# Generated by tools/costs/stdlib-fuel.ts. Do not edit.\n' +
    '# Each stdlib export’s Fuel Estimate. A change here is a Cost Model change.\n\n' +
    blocks.join('\n\n') +
    '\n'
  );
};

if (import.meta.main) {
  const text = stdlibFuel();
  if (process.argv.includes('--check')) {
    const file = Bun.file(path);
    if (!(await file.exists()) || (await file.text()) !== text) {
      throw new Error(
        'The stdlib Fuel snapshot is stale; run bun run stdlib-fuel:generate',
      );
    }
  } else {
    await Bun.write(path, text);
  }
}
