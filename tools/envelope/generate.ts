#!/usr/bin/env bun
// Tables only: codecs retain validation, traversal and JSON reshaping.
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { format } from 'prettier';
import { formatGo, writeOutput } from '../go/output';
import {
  envelopeViews,
  validateCatalogue,
  type Catalogue,
  type Entry,
  type Field,
  type Vector,
} from './catalogue';

const root = resolve(import.meta.dir, '../..');
const header = 'Code generated by tools/envelope/generate.ts. DO NOT EDIT.';
const quote = (value: unknown): string => JSON.stringify(value);
const kinds = (d: Catalogue) =>
  [
    ...new Set(
      [...d.messages, ...d.reports, d.settlement].flatMap(e =>
        e.fields.map(f => f.kind),
      ),
    ),
  ].sort();

export const emitTypeScript = async (data: Catalogue) =>
  format(
    `// ${header}
export type EnvelopeKind = ${kinds(data).map(quote).join(' | ')};
export type EnvelopeField = { readonly name: string; readonly kind: EnvelopeKind; readonly required: boolean };
export type EnvelopeEntry = { readonly tag: number; readonly name: string; readonly direction: 'host-to-guest' | 'guest-to-host'; readonly fields: readonly EnvelopeField[] };
export const envelopeFeatures = ${quote(data.features)} as const;
export const envelopeMessages: readonly EnvelopeEntry[] = ${quote(data.messages)};
export const envelopeReports: readonly EnvelopeEntry[] = ${quote(data.reports)};
export const envelopeSettlement: readonly EnvelopeField[] = ${quote(data.settlement.fields)};
`,
    { parser: 'typescript', singleQuote: true, trailingComma: 'all' },
  );

export const emitGo = (data: Catalogue): string => {
  const fields = (fs: Field[]) =>
    `[]EnvelopeField{${fs.map(f => `{Name:${quote(f.name)}, Kind:${quote(f.kind)}, Required:${f.required}}`).join(',')}}`;
  const entries = (es: Entry[]) =>
    `[]EnvelopeEntry{${es.map(e => `{Tag:${e.tag}, Name:${quote(e.name)}, Direction:${quote(e.direction)}, Fields:${fields(e.fields)}}`).join(',')}}`;
  return formatGo(`// ${header}
package generated
type EnvelopeField struct { Name string; Kind string; Required bool }
type EnvelopeEntry struct { Tag byte; Name string; Direction string; Fields []EnvelopeField }
var EnvelopeFeatures = []string{${data.features.map(quote).join(',')}}
var EnvelopeMessages = ${entries(data.messages)}
var EnvelopeReports = ${entries(data.reports)}
var EnvelopeSettlement = ${fields(data.settlement.fields)}
`);
};

export const emitZig = (data: Catalogue): string => {
  const fields = (fs: Field[]) =>
    `&.{ ${fs.map(f => `.{ .name = ${quote(f.name)}, .kind = .${f.kind}, .required = ${f.required} }`).join(', ')} }`;
  const entries = (es: Entry[]) =>
    `&.{\n${es.map(e => `    .{ .tag = 0x${e.tag.toString(16)}, .name = ${quote(e.name)}, .direction = .${e.direction.replaceAll('-', '_')}, .fields = ${fields(e.fields)} },`).join('\n')}\n}`;
  return `// ${header}
pub const Kind = enum { ${kinds(data).join(', ')} };
pub const Direction = enum { host_to_guest, guest_to_host };
pub const Field = struct { name: []const u8, kind: Kind, required: bool };
pub const Entry = struct { tag: u8, name: []const u8, direction: Direction, fields: []const Field };
pub const features: []const []const u8 = &.{ ${data.features.map(quote).join(', ')} };
pub const messages: []const Entry = ${entries(data.messages)};
pub const reports: []const Entry = ${entries(data.reports)};
pub const settlement: []const Field = ${fields(data.settlement.fields)};
`;
};

export const emitElixir = (data: Catalogue): string => {
  const fields = (fs: Field[], indent: number, prefix: string) => {
    const rows = fs.map(
      f =>
        `%{name: ${quote(f.name)}, kind: :${f.kind}, required: ${f.required}}`,
    );
    const inline = `[${rows.join(', ')}]`;
    return indent + prefix.length + inline.length <= 120
      ? inline
      : `[\n${rows.map(row => ' '.repeat(indent + 2) + row).join(',\n')}\n${' '.repeat(indent)}]`;
  };
  const entries = (es: Entry[]) =>
    `[\n${es.map(e => `    %{\n      tag: ${e.tag},\n      name: ${quote(e.name)},\n      direction: :${e.direction.replaceAll('-', '_')},\n      fields: ${fields(e.fields, 6, 'fields: ')}\n    }`).join(',\n')}\n  ]`;
  return `# ${header}
defmodule NorthTalk.Generated.Envelope do
  @moduledoc false
  @features [${data.features.map(quote).join(', ')}]
  @messages ${entries(data.messages)}
  @reports ${entries(data.reports)}
  @settlement ${fields(data.settlement.fields, 2, '@settlement ')}
  def features, do: @features
  def messages, do: @messages
  def reports, do: @reports
  def settlement, do: @settlement
end
`;
};

export const generate = async (check: boolean) => {
  const data: unknown = Bun.TOML.parse(
    await readFile(resolve(root, 'spec/data/envelope.toml'), 'utf8'),
  );
  validateCatalogue(data);
  const vectors = JSON.parse(
    await readFile(resolve(root, 'impl/testdata/envelope-frames.json'), 'utf8'),
  ) as Vector[];
  // Coverage inspects actual frame bytes and decoded Reports, not a declared tag alone.
  const { checkVectors } = await import('./vectors');
  checkVectors(data, vectors);
  const documentPath = resolve(root, 'spec/embedding/request-pump-binary.md');
  let document = await readFile(documentPath, 'utf8');
  for (const [name, view] of Object.entries(envelopeViews(data))) {
    const marker = `<!-- generated: ${name} -->`;
    const start = document.indexOf(marker);
    const end = document.indexOf('<!-- end -->', start);
    if (start < 0 || end < 0 || document.indexOf(marker, start + 1) >= 0) {
      throw new Error(`Missing or duplicate region ${name}`);
    }
    document =
      document.slice(0, start) +
      `${marker}\n\n${view}\n\n` +
      document.slice(end);
  }
  const outputs: [string, string][] = [
    ['impl/ts/src/generated/envelope.ts', await emitTypeScript(data)],
    ['impl/go/internal/generated/envelope.go', emitGo(data)],
    ['impl/zig/src/generated/envelope.zig', emitZig(data)],
    ['impl/elixir/lib/north_talk/generated/envelope.ex', emitElixir(data)],
    ['spec/embedding/request-pump-binary.md', document],
  ];
  for (const [path, content] of outputs) {
    await writeOutput(
      resolve(root, path),
      content,
      check,
      'bun run envelope:generate',
    );
  }
  console.log(
    `Envelope: ${data.messages.length} messages, ${data.reports.length} Reports, ${vectors.length} vectors; tables ${check ? 'match' : 'generated'}`,
  );
};

if (import.meta.main) {
  await generate(process.argv.includes('--check'));
}
