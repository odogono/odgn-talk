const root = resolve(import.meta.dir, '../..');
const header = 'Code generated by tools/envelope/generate.ts. DO NOT EDIT.';
const quote = (value: unknown): string => JSON.stringify(value);
const words = (feature: string) => feature.split('-');
const camel = (feature: string) =>
  words(feature)
    .map((w, i) => (i === 0 ? w : w[0]!.toUpperCase() + w.slice(1)))
    .join('');
const pascal = (feature: string) =>
  words(feature)
    .map(w => w[0]!.toUpperCase() + w.slice(1))
    .join('');
const snake = (feature: string) => words(feature).join('_');
const kinds = (d: Catalogue) =>
  [
    ...new Set(
      [
        ...d.messages,
        ...d.reports,
        d.settlement,
        ...d.json_messages,
        ...d.views,
      ].flatMap(e => e.fields.map(f => f.kind)),
    ),
  ].sort();

export const emitTypeScript = async (data: Catalogue) =>
  format(
    `// ${header}
import type { Json } from '../readers';
export type EnvelopeKind = ${kinds(data).map(quote).join(' | ')};
export type EnvelopeField = { readonly name: string; readonly kind: EnvelopeKind; readonly required: boolean; readonly host?: boolean; readonly view?: string };
export type EnvelopeJsonMessage = { readonly name: string; readonly direction: 'host-to-guest' | 'guest-to-host'; readonly reply?: string; readonly fields: readonly EnvelopeField[] };
export type EnvelopeView = { readonly name: string; readonly fields: readonly EnvelopeField[] };
export type EnvelopeEntry = { readonly tag: number; readonly name: string; readonly direction: 'host-to-guest' | 'guest-to-host'; readonly layouts?: readonly ('fields' | 'json')[]; readonly fields: readonly EnvelopeField[] };
export const envelopeFeatures = ${quote(data.features)} as const;
export const envelopeFeature = { ${data.features.map(f => `${camel(f)}: ${quote(f)}`).join(', ')} } as const;
export const envelopeMessages: readonly EnvelopeEntry[] = ${quote(data.messages)};
export const envelopeReports: readonly EnvelopeEntry[] = ${quote(data.reports)};
export const envelopeSettlement: readonly EnvelopeField[] = ${quote(data.settlement.fields)};
export const envelopeJsonMessages: readonly EnvelopeJsonMessage[] = ${quote(data.json_messages)};
export const envelopeViews: readonly EnvelopeView[] = ${quote(data.views)};
${emitTypeScriptRecords(data)}
`,
    { parser: 'typescript', singleQuote: true, trailingComma: 'all' },
  );

export const emitGo = (data: Catalogue): string => {
  const fields = (fs: Field[]) =>
    `[]EnvelopeField{${fs.map(f => `{Name:${quote(f.name)}, Kind:${quote(f.kind)}, Required:${f.required}${f.host === false ? ', HostFilled:true' : ''}${f.view ? `, View:${quote(f.view)}` : ''}}`).join(',')}}`;
  const entries = (es: Entry[]) =>
    `[]EnvelopeEntry{${es.map(e => `{Tag:${e.tag}, Name:${quote(e.name)}, Direction:${quote(e.direction)}, Layouts:[]string{${('layouts' in e ? (e as { layouts: string[] }).layouts : []).map(quote).join(',')}}, Fields:${fields(e.fields)}}`).join(',')}}`;
  return formatGo(`// ${header}
package generated
// EnvelopeField describes one field. HostFilled marks a field the Host fills
// itself rather than from a public option; View names a views field's items.
type EnvelopeField struct { Name string; Kind string; Required bool; HostFilled bool; View string }
type EnvelopeEntry struct { Tag byte; Name string; Direction string; Layouts []string; Fields []EnvelopeField }
type EnvelopeJSONMessage struct { Name string; Direction string; Reply string; Fields []EnvelopeField }
type EnvelopeView struct { Name string; Fields []EnvelopeField }
var EnvelopeFeatures = []string{${data.features.map(quote).join(',')}}
const (
${data.features.map(f => `EnvelopeFeature${pascal(f)} = ${quote(f)}`).join('\n')}
)
var EnvelopeMessages = ${entries(data.messages)}
var EnvelopeReports = ${entries(data.reports)}
var EnvelopeSettlement = ${fields(data.settlement.fields)}
var EnvelopeJSONMessages = []EnvelopeJSONMessage{${data.json_messages.map(m => `{Name:${quote(m.name)}, Direction:${quote(m.direction)}, Reply:${quote(m.reply ?? '')}, Fields:${fields(m.fields)}}`).join(',')}}
var EnvelopeViews = []EnvelopeView{${data.views.map(v => `{Name:${quote(v.name)}, Fields:${fields(v.fields)}}`).join(',')}}
${emitGoRecords(data)}
`);
};

// zig fmt drops the spaces inside a one-item initializer.
const zigLayouts = (e: Entry) => {
  const ls = 'layouts' in e ? (e as MessageEntry).layouts : [];
  return ls.length === 1
    ? `&.{.${ls[0]}}`
    : ls.length === 0
      ? '&.{}'
      : `&.{ ${ls.map(l => `.${l}`).join(', ')} }`;
};
export const emitZig = (data: Catalogue): string => {
  const field = (f: Field) =>
    `.{ .name = ${quote(f.name)}, .kind = .${f.kind}, .required = ${f.required}${f.host === false ? ', .host = false' : ''}${f.view ? `, .view = ${quote(f.view)}` : ''} }`;
  // zig fmt drops the spaces inside a one-item initializer.
  const fields = (fs: Field[]) =>
    fs.length === 1
      ? `&.{${field(fs[0]!)}}`
      : `&.{ ${fs.map(field).join(', ')} }`;

  const entries = (es: Entry[]) =>
    `&.{\n${es.map(e => `    .{ .tag = 0x${e.tag.toString(16)}, .name = ${quote(e.name)}, .direction = .${e.direction.replaceAll('-', '_')}, .layouts = ${zigLayouts(e)}, .fields = ${fields(e.fields)} },`).join('\n')}\n}`;
  return `// ${header}
const std = @import("std");

pub const Kind = enum { ${kinds(data).join(', ')} };
pub const Direction = enum { host_to_guest, guest_to_host };
pub const Field = struct { name: []const u8, kind: Kind, required: bool, host: bool = true, view: ?[]const u8 = null };
pub const JsonMessage = struct { name: []const u8, direction: Direction, reply: ?[]const u8 = null, fields: []const Field };
pub const View = struct { name: []const u8, fields: []const Field };
pub const Layout = enum { fields, json };
pub const Entry = struct { tag: u8, name: []const u8, direction: Direction, layouts: []const Layout, fields: []const Field };
pub const features: []const []const u8 = &.{ ${data.features.map(quote).join(', ')} };
pub const feature = struct {
${data.features.map(f => `    pub const ${snake(f)} = ${quote(f)};`).join('\n')}
};
pub const messages: []const Entry = ${entries(data.messages)};
pub const reports: []const Entry = ${entries(data.reports)};
pub const settlement: []const Field = ${fields(data.settlement.fields)};
pub const json_messages: []const JsonMessage = &.{
${data.json_messages.map(m => `    .{ .name = ${quote(m.name)}, .direction = .${m.direction.replaceAll('-', '_')},${m.reply ? ` .reply = ${quote(m.reply)},` : ''} .fields = ${fields(m.fields)} },`).join('\n')}
};
pub const views: []const View = &.{
${data.views.map(v => `    .{ .name = ${quote(v.name)}, .fields = ${fields(v.fields)} },`).join('\n')}
};

${emitZigRecords(data)}
`;
};

export const emitElixir = (data: Catalogue): string => {
  const fields = (fs: Field[], indent: number, prefix: string) => {
    const rows = fs.map(
      f =>
        `%{name: ${quote(f.name)}, kind: :${f.kind}, required: ${f.required}}`,
    );
    const inline = `[${rows.join(', ')}]`;
    return indent + prefix.length + inline.length <= 120
      ? inline
      : `[\n${rows.map(row => ' '.repeat(indent + 2) + row).join(',\n')}\n${' '.repeat(indent)}]`;
  };
  const inlineFeatures = `[${data.features.map(quote).join(', ')}]`;
  const features =
    '  @features '.length + inlineFeatures.length <= 120
      ? inlineFeatures
      : `[\n${data.features.map(f => `    ${quote(f)}`).join(',\n')}\n  ]`;
  const entries = (es: Entry[]) =>
    `[\n${es.map(e => `    %{\n      tag: ${e.tag},\n      name: ${quote(e.name)},\n      direction: :${e.direction.replaceAll('-', '_')},\n      layouts: [${('layouts' in e ? (e as { layouts: string[] }).layouts : []).map(l => `:${l}`).join(', ')}],\n      fields: ${fields(e.fields, 6, 'fields: ')}\n    }`).join(',\n')}\n  ]`;
  return `# ${header}
defmodule NorthTalk.Generated.Envelope do
  @moduledoc false
  @features ${features}
  @messages ${entries(data.messages)}
  @reports ${entries(data.reports)}
  @settlement ${fields(data.settlement.fields, 2, '@settlement ')}
  def features, do: @features
${data.features.map(f => `  def feature(:${snake(f)}), do: ${quote(f)}`).join('\n')}
  def messages, do: @messages
  def reports, do: @reports
  def settlement, do: @settlement
end

${emitElixirRecords(data)}
`;
};

export const generate = async (check: boolean) => {
  const data: unknown = Bun.TOML.parse(
    await readFile(resolve(root, 'spec/data/envelope.toml'), 'utf8'),
  );
  validateCatalogue(data);
  const vectors = JSON.parse(
    await readFile(resolve(root, 'impl/testdata/envelope-frames.json'), 'utf8'),
  ) as Vector[];
  // Coverage inspects actual frame bytes and decoded Reports, not a declared tag alone.
  const { checkVectors } = await import('./vectors');
  checkVectors(data, vectors);
  const { checkMethodTable } = await import('./table');
  checkMethodTable(
    data,
    await readFile(resolve(root, 'spec/09-embedding.md'), 'utf8'),
  );
  const documentPath = resolve(root, 'spec/embedding/request-pump-binary.md');
  let document = await readFile(documentPath, 'utf8');
  for (const [name, view] of Object.entries(envelopeViews(data))) {
    const marker = `<!-- generated: ${name} -->`;
    const start = document.indexOf(marker);
    const end = document.indexOf('<!-- end -->', start);
    if (start < 0 || end < 0 || document.indexOf(marker, start + 1) >= 0) {
      throw new Error(`Missing or duplicate region ${name}`);
    }
    document =
      document.slice(0, start) +
      `${marker}\n\n${view}\n\n` +
      document.slice(end);
  }
  const outputs: [string, string][] = [
    ['impl/ts/src/generated/envelope.ts', await emitTypeScript(data)],
    ['impl/go/internal/generated/envelope.go', emitGo(data)],
    ['impl/zig/src/generated/envelope.zig', emitZig(data)],
    ['impl/elixir/lib/north_talk/generated/envelope.ex', emitElixir(data)],
    ['spec/embedding/request-pump-binary.md', document],
  ];
  for (const [path, content] of outputs) {
    await writeOutput(
      resolve(root, path),
      content,
      check,
      'bun run envelope:generate',
    );
  }
  console.log(
    `Envelope: ${data.messages.length} messages, ${data.reports.length} Reports, ${vectors.length} vectors; tables ${check ? 'match' : 'generated'}`,
  );
};

if (import.meta.main) {
  await generate(process.argv.includes('--check'));
}
